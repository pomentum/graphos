"""Write the graphos website's page, docs/index.html, from tools/docs/site.html.

GitHub Pages serves ``docs/`` of ``main`` as it is, at https://www.pomentum.dev/graphos/
(Settings -> Pages -> Deploy from a branch, ``main``, ``/docs``): no build runs there.
The page is generated here, like the diagrams, and committed. Beside it in ``docs/`` sit
its stylesheet and theme switch (``site.css``, ``site.js``),
``favicon.svg``, ``404.html`` and ``.nojekyll``; its pictures are ``docs/images/``.

The frame, ``tools/docs/site.html``, has ``{{ name }}`` slots this script fills from files
the repository already has, so nothing on the page is written twice:

- six of the README's features (:data:`PAGE_FEATURES`), its web UI screenshots and captions, and
  documentation table; the installation guide's install commands (its §2);
- the version from ``services/graphos/pyproject.toml``;
- the alt text of each diagram it shows, from the ``<desc>`` that ``diagrams.mjs`` writes
  into ``docs/images/<name>-light.svg``.

Links into the repository (``docs/guide/usage.md``) point to GitHub. The script fails when a
slot is left unfilled or a local link or picture points at a file ``docs/`` does not have.

    python tools/docs/site.py           # write docs/index.html
    python tools/docs/site.py --check   # exit 1 when docs/index.html is not what it writes
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

REPO = Path(__file__).resolve().parents[2]
FRAME = REPO / "tools" / "docs" / "site.html"
DOCS = REPO / "docs"
PAGE = DOCS / "index.html"
GITHUB = "https://github.com/pomentum/graphos"
GENERATED = "<!-- Generated by tools/docs/site.py from tools/docs/site.html and the README. -->\n"
# README sections the page does not show, and where they live instead.
README_ANCHORS = {"#python-client": f"{GITHUB}/tree/main/clients/python", "#web-ui": "#ui"}
DOCS_COLUMNS = 2  # the README's documentation table: | Doc | Read it for |


def repo_link(target: str, base: str = "") -> str:
    """Return a link from a README or doc, made to work from the site's root."""
    if target in README_ANCHORS:
        return README_ANCHORS[target]
    if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("#"):
        return target
    path, hash_, fragment = target.partition("#")
    path = str(Path(base, path).as_posix()).removeprefix("./")
    if path.startswith("docs/images/"):
        return path.removeprefix("docs/")
    kind = "tree" if (REPO / path).is_dir() else "blob"
    return f"{GITHUB}/{kind}/main/{path}{hash_}{fragment}"


_LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


def inline(md: str) -> str:
    """Render the inline Markdown the README uses: code, bold, italics and links. Links
    first, so a link's text may hold code (``[`graphos-client`](…)``)."""
    parts = _LINK.split(md)                     # text, link text, link target, text, …
    out = [_spans(parts[0])]
    for i in range(1, len(parts), 3):
        text, target, after = parts[i], parts[i + 1], parts[i + 2]
        out.append(f'<a href="{html.escape(repo_link(target))}">{_spans(text)}</a>')
        out.append(_spans(after))
    return "".join(out)


def _spans(md: str) -> str:
    """Code, bold and italics."""
    out: list[str] = []
    for i, part in enumerate(re.split(r"(`[^`]+`)", md)):
        if i % 2:
            out.append(f"<code>{html.escape(part[1:-1])}</code>")
            continue
        text = html.escape(part, quote=False)
        text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
        text = re.sub(r"(?<![\w*])\*([^*]+)\*(?![\w*])", r"<em>\1</em>", text)
        out.append(text)
    return "".join(out)


def sections(markdown: str) -> dict[str, str]:
    """Split a Markdown file into its ``##`` sections, by lower-case title."""
    parts: dict[str, str] = {}
    for block in markdown.split("\n## ")[1:]:
        title, _, body = block.partition("\n")
        parts[title.strip().lower()] = body
    return parts


# The README's features the page shows, in this order: what sets graphos apart. The README
# lists them all; the page links the rest through the feature survey.
PAGE_FEATURES = (
    "Tenants and schema",
    "Fast, idempotent writes",
    "Reconcile by difference",
    "Graph algorithms",
    "AI agents (MCP)",
    "Change feed",
)


def features(body: str) -> str:
    """The README's features named in :data:`PAGE_FEATURES`, as one grid of cards."""
    cards: dict[str, str] = {}
    for line in body.splitlines():
        if item := re.match(r"- \*\*(.+?):\*\* (.*)", line):
            text = item.group(2)[:1].upper() + item.group(2)[1:]
            cards[item.group(1)] = (
                f'<div class="card"><h4>{inline(item.group(1))}</h4><p>{inline(text)}</p></div>'
            )
    if missing := [name for name in PAGE_FEATURES if name not in cards]:
        raise SystemExit(f"the README's features have no {missing}")
    return '<div class="cards">\n' + "\n".join(cards[n] for n in PAGE_FEATURES) + "\n</div>"


def png_size(path: Path) -> tuple[int, int]:
    """A PNG's width and height, from its header."""
    head = path.read_bytes()[16:24]
    return int.from_bytes(head[:4], "big"), int.from_bytes(head[4:], "big")


def shots(body: str) -> str:
    """The README's web UI screenshots, each with its alt text and caption: the WebP copy
    screenshots.py writes beside each PNG, a quarter of its size, and the PNG for a browser
    without WebP, with the PNG's own size (a shot may be of one dialog, not the window). Each
    opens full size on a click; the stylesheet shows the first one across the whole grid."""
    out: list[str] = []
    pairs = re.findall(
        r'<img src="([^"]+)" width="100%" alt="([^"]+)">\s*\n\s*\*(.+?)\*\s*\n', body
    )
    for n, (src, alt, caption) in enumerate(pairs, 1):
        png = repo_link(src)
        width, height = png_size(DOCS / png)
        out.append(
            f'<figure class="fig"><a class="zoom" href="{png}" title="Open full size">'
            f'<picture><source type="image/webp" srcset="{png.removesuffix(".png")}.webp">'
            f'<img class="shot" src="{png}" alt="{alt}" loading="lazy" width="{width}" '
            f'height="{height}"></picture></a><figcaption><span class="fig-n">'
            f"UI {n:02d}</span><span>{inline(caption)}</span></figcaption></figure>"
        )
    return "\n".join(out)


def first_code_block(body: str) -> str:
    """The first fenced code block of a section, escaped for a ``<pre>``."""
    m = re.search(r"```\w*\n(.*?)\n```", body, re.DOTALL)
    if not m:
        raise SystemExit("README Quickstart has no code block")
    return html.escape(m.group(1))


def docs_table(body: str) -> str:
    """The README's documentation table, as rows of links and what each is for."""
    rows: list[str] = []
    for line in body.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != DOCS_COLUMNS or not cells[0].startswith("["):
            continue
        name = re.match(r"\[([^\]]+)\]\(([^)]+)\)", cells[0])
        if not name:
            continue
        label, target = name.groups()
        rows.append(
            f'<div><dt><a href="{repo_link(target)}">{html.escape(label)}</a></dt>'
            f"<dd>{inline(cells[1])}</dd></div>"
        )
    return "\n".join(rows)


def version() -> str:
    """The version the service, client and UI share."""
    text = (REPO / "services" / "graphos" / "pyproject.toml").read_text(encoding="utf-8")
    m = re.search(r'^version = "([^"]+)"', text, re.MULTILINE)
    if not m:
        raise SystemExit("no version in services/graphos/pyproject.toml")
    return m.group(1)


def check_links(page: str) -> list[str]:
    """Local links and pictures of the page that ``docs/`` does not have, and
    links to a place in the page that no element's ``id`` names."""
    missing: list[str] = []
    ids = set(re.findall(r'\sid="([^"]+)"', page))
    for target in re.findall(r'(?:href|src|srcset)="([^"]+)"', page):
        url = urlsplit(target)
        if not (url.scheme or url.netloc or url.path):
            if url.fragment and url.fragment not in ids:
                missing.append(target)
            continue
        if url.scheme or url.netloc or not url.path:
            continue
        path = DOCS / url.path
        if url.path.endswith("/"):
            path = path / "index.html"
        if not path.exists():
            missing.append(target)
    return missing


def diagram_alt(name: str) -> str:
    """A diagram's alt text: the description diagrams.mjs gave it, as an attribute value."""
    svg = (DOCS / "images" / f"{name}-light.svg").read_text(encoding="utf-8")
    m = re.search(r"<desc[^>]*>(.*?)</desc>", svg, re.DOTALL)
    if not m:
        raise SystemExit(f"docs/images/{name}-light.svg has no <desc>")
    return html.escape(html.unescape(" ".join(m.group(1).split())))


def render() -> str:
    """The page, its slots filled from the README and the version."""
    readme = sections((REPO / "README.md").read_text(encoding="utf-8"))
    guide = sections((REPO / "docs" / "guide" / "installation.md").read_text(encoding="utf-8"))
    values = {
        "version": version(),
        "features": features(readme["features"]),
        "shots": shots(readme["web ui"]),
        # The installation guide's install, not the README's quickstart: the page signs
        # people in through the UI, so it needs no API sign-in step.
        "quickstart": first_code_block(guide["2. install with docker compose"]),
        "docs": docs_table(readme["documentation"]),
        "alt_problem": diagram_alt("problem"),
        "alt_communities": diagram_alt("communities"),
    }
    frame = FRAME.read_text(encoding="utf-8")
    page = re.sub(r"\{\{ (\w+) \}\}", lambda m: values[m.group(1)], frame)
    if leftover := re.findall(r"\{\{ \w+ \}\}", page):
        raise SystemExit(f"unfilled slots: {leftover}")
    doctype, _, rest = page.partition("\n")
    return f"{doctype}\n{GENERATED}{rest}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only check docs/index.html")
    args = parser.parse_args()

    page = render()
    if missing := check_links(page):
        print("links to files docs/ does not have:", *missing, sep="\n  ", file=sys.stderr)
        return 1
    if args.check:
        current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if current != page:
            print("docs/index.html is out of date: run python tools/docs/site.py", file=sys.stderr)
            return 1
        print("site: docs/index.html matches")
        return 0
    PAGE.write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {PAGE.relative_to(REPO).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
